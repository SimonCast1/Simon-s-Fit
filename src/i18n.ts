const DICTS: Record<'pt' | 'en', Dict> = { pt, en };
export type TFn = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(lang: 'pt' | 'en'): TFn {
  const d = DICTS[lang];
  return (key, vars) => {
    const k1 = vars?.n === 1 ? `${key}.one` : '';
    let s = (k1 && (d[k1] ?? DICTS.en[k1])) || d[key] || DICTS.en[key] || key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

